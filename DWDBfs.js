      obj.archive = false
      obj.id = orderId
      obj.status = status
      obj.statusDate = transDate
      obj.route = null
      obj.transactions = []
      obj.items = itemsObj
      obj.isPaid = false
      obj.paymentMethod = PaymentMethodEnum.initial.enumKey
      obj.paymentDetails = {}
      obj.notes = []        // notes: [...dbOrder.notes],
      // obj.routesArray = [fauxOrder.pickupRouteTime, fauxOrder.deliveryRouteTime] //SCSC
      obj.routesArray = [fauxOrder.pickupRouteId, fauxOrder.deliveryRouteId]
      obj.transactions = firestore.FieldValue.arrayUnion({
         status: status,
         prevStatus: null,
         transDate: transDate
      })
      newRef = firestore().collection('Orders').doc(orderId.toString())
      trnx.set(newRef, obj)

      if (['applies','maybe'].includes (fauxOrder.couponStatus)){
      await trnx.update(firestore().collection("Coupons").doc(fauxOrder.coupon.docId), {'isUsed':true })

      }

