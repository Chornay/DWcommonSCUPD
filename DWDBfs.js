//perform an action on the route
//NOTE that status is enum internally but string in DB
//for some status changes we record the time in the base fields
//in all cases we record the status change as a transaction
export async function dwdbfsRouteAction(route, orders, action) {
   const transTime = new Date();
   const currStatus = route.status.enumKey;
   var batch = firestore().batch()
   let newStatus = null
   switch (action) {
      case RouteActionEnum.lock:
         newStatus = RouteStatusEnum.locked
         break;
      case RouteActionEnum.unlock:
         newStatus = RouteStatusEnum.pending
         break;
      case RouteActionEnum.open: // change status of all orders appropriately
         // console.log('action open')
         newStatus = RouteStatusEnum.open
         orders.forEach((order) => {
            switch (order.status) {
               case OrderStatusEnum.assignedForPickup:
               case OrderStatusEnum.readyForPickup:
                  dwdbfsOrderUpdateStatusWithinBatch(batch, order.docId, order.status, OrderStatusEnum.outForPickup, transTime)
                  break;
               case OrderStatusEnum.assignedForDelivery:
               case OrderStatusEnum.readyForDelivery:
                  dwdbfsOrderUpdateStatusWithinBatch(batch, order.docId, order.status, OrderStatusEnum.outForDelivery, transTime)
                  break;
            }

         })

         break;
      case RouteActionEnum.close: //all pickups marked as atShop
         newStatus = RouteStatusEnum.completed//TODO what about ActionRequired?
         orders.forEach((order) => {
            switch (order.status) {
               case OrderStatusEnum.assignedForPickup:
               case OrderStatusEnum.readyForPickup:
               case OrderStatusEnum.outForPickup:
                  //TODO remove from from route?? because not picked up
                  break;
               case OrderStatusEnum.pickedUp:
                  dwdbfsOrderUpdateStatusWithinBatch(batch, order.docId, order.status, OrderStatusEnum.atShop, transTime)
                  break;
               default:
                  //TODO maybe everything has to be removed
                  break;
            }

         })

         break;
   } // end route action switch

   if (newStatus) {
      // console.log("route update", route.shopId, route.docId)
      const routeRef = firestore().collection("ShopTop").doc(route.shopId).collection('Routes').doc(route.docId)
      batch.update(routeRef, {
         status: newStatus.enumKey,
         statusDate: transTime,
         // transactions: firestore.FieldValue.arrayUnion({
         //   status: newStatus.enumKey,
         //   prevStatus: currStatus.enumKey,
         //   transDate: transTime
         // })
         transactions: firestore.FieldValue.arrayUnion({ xyz: '1234' })
      })
   }
   await batch.commit()
}//end dwdbfsRouteAction

