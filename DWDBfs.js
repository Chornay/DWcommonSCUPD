      let newRef
      let transDate = new Date()
      //if we have a pickup route assigned original status is assignedForPickup ow readyForPickup
      let status = fauxOrder.pickupRouteTime ? OrderStatusEnum.assignedForPickup.enumKey
         : OrderStatusEnum.readyForPickup.enumKey
      let { routesArray, transactions, items, notes, ...obj } = fauxOrder
