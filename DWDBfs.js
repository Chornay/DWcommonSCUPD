//extracts an order from an order document snapshot
export function dwdbfsOrderExtract(dbOrder) {
   let { status,
      paymentMethod,
      transactions,
      items,
      notes,
      pickupRouteTime,
      deliveryRouteTime,
      ...order } = dbOrder

   order.pickupRouteTime = dbOrder.pickupRouteTime ? dbOrder.pickupRouteTime.toDate() : null
   order.deliveryRouteTime = dbOrder.deliveryRouteTime ? dbOrder.deliveryRouteTime.toDate() : null
   order.status = OrderStatusEnum.enumValueOf(dbOrder.status)
   order.paymentMethod = PaymentMethodEnum.enumValueOf(dbOrder.paymentMethod)
   order.transactions = []
   order.items = []
   order.notes = []
   order.docId = dbOrder.id //TODO we really shouldn't need this field .. DEPRECATED
   order.selected = false
   order.distance = 0.0


   //extract the order items from database item  { code1:{category1:nnn,unitType1:nnn,etc}, 
   //                                              code2:{category2:nnn,unitType2:nnn,etc},
   //                                                  etc                          }
   Object.entries(dbOrder.items).forEach((dbItem) => {
      let item = {}
      item = dbItem[1]
      item.code = dbItem[0]
      item.key = dbItem[0] //20220320
      order.items.push(item)
   })


   dbOrder.transactions.forEach((dbTrans) => {
      let trans = {}
      trans.transDate = dbTrans.transDate.toDate()
      trans.status = dbTrans.status
      trans.prevStatus = dbTrans.prevStatus
      trans.strX = dbTrans.strX
      order.transactions.push(trans)
   })

   return order
} //end dwdbfsOrderExtract

