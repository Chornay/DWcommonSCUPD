//run a transaction to get the next sequential customer id
//by incrementing Counters.SHOP-xxxxx.lastAlloc
//throws error if problem
export async function dwdbfsOrderGenerateNewId(shopId) {
   let currId
   let divider
   const ctrDocRef = firestore().collection('ShopTop').doc(shopId.toString())
   await firestore().runTransaction(async trnx => {
      const shopDoc = await trnx.get(ctrDocRef)
      if (!shopDoc.exists) { throw "Unable to access Shop counters document" }
      if (!shopDoc.data().hasOwnProperty('lastAlloc')) { throw "Unable to access Shop Order Counter" }
      currId = shopDoc.data().lastAlloc + 1
      divider = shopDoc.data().divider
      await trnx.update(ctrDocRef, { lastAlloc: currId })
   })
   return shopId.toString() + "-" + divider + "-" + currId.toString().padStart(5, '0')
}// end dwdbfsOrderGenerateNewId

